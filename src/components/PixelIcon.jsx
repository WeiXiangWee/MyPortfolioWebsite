export function PixelIcon({ name, size = 16 }) {
  const rows = ICONS[name];
  if (!rows) return null;
  const rects = [];
  rows.forEach((row, y) =>
    [...row].forEach((c, x) => {
      if (c === '#') rects.push(<rect key={`${x}-${y}`} x={x} y={y} width="1" height="1" />);
    }),
  );
  return (
    <svg className="pixel-icon" viewBox="0 0 12 12" width={size} height={size} shapeRendering="crispEdges" fill="currentColor" aria-hidden="true" focusable="false">
      {rects}
    </svg>
  );
}
